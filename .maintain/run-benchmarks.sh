#!/usr/bin/env bash
#
# Regenerate weight files from the benchmarks the runtime exposes. Pass pallet
# names to narrow the run, otherwise every benchmarked pallet is rebuilt.
#
# The pallet list comes from the runtime itself rather than a copy kept here,
# so adding an entry to `define_benchmarks!` is all it takes to get covered.
set -euo pipefail

cd "$(dirname "$0")/.."

STEPS=${STEPS:-50}
REPEAT=${REPEAT:-20}
# The node binary doubles as the bench host so both sides of the
# benchmarking FFI come out of one build. A separately installed
# frame-omni-bencher can drift from the locked SDK rev and break it.
# Weights must come off the same production profile wasm the release
# binaries ship.
BINARY=${BINARY:-./target/production/numen}
RUNTIME=${RUNTIME:-target/production/wbuild/numen-runtime/numen_runtime.compact.compressed.wasm}

if [[ ! -x $BINARY || ! -f $RUNTIME ]]; then
	echo "missing build artefacts, run:" >&2
	echo "  cargo build --profile production --locked -p numen --features runtime-benchmarks" >&2
	exit 1
fi

# Pallets owned by this repo keep their weights beside the code so each crate
# stays usable on its own. Everything else lands under runtime/src/weights.
declare -A OWN=(
	[pallet_difficulty]=pallets/difficulty/src/weights.rs
	[pallet_prime]=pallets/prime/src/weights.rs
	[pallet_reward]=pallets/reward/src/weights.rs
	[pallet_validator]=pallets/validator/src/weights.rs
)

common=(
	--runtime "$RUNTIME"
	--genesis-builder=runtime
	--genesis-builder-preset=development
)

if (($#)); then
	pallets=("$@")
else
	mapfile -t pallets < <("$BINARY" benchmark pallet "${common[@]}" --list=pallets | tail -n +2 | sort -u)
fi

mkdir -p runtime/src/weights

# One broken pallet must not hide the state of the rest, so failures are
# collected and reported at the end instead of aborting the sweep.
failed=()

for pallet in "${pallets[@]}"; do
	# The baseline bench measures the host, it backs no dispatchable.
	[[ $pallet == frame_benchmarking ]] && continue

	# Own pallets need the template that also defines the trait. Everything
	# else takes the CLI builtin, which targets `{{pallet}}::WeightInfo`.
	template_args=()
	if [[ -v OWN[$pallet] ]]; then
		template_args=(--template .maintain/frame-weight-template.hbs)
		output=${OWN[$pallet]}
	else
		output=runtime/src/weights/$pallet.rs
	fi

	echo "==> $pallet -> $output"
	if ! "$BINARY" benchmark pallet "${common[@]}" \
		--pallet "$pallet" \
		--extrinsic '*' \
		--steps "$STEPS" \
		--repeat "$REPEAT" \
		"${template_args[@]}" \
		--output "$output"; then
		failed+=("$pallet")
	fi
done

{
	echo "//! Weights measured against this runtime. Regenerated by"
	echo "//! \`.maintain/run-benchmarks.sh\`, do not edit by hand."
	echo
	for file in runtime/src/weights/*.rs; do
		name=$(basename "$file" .rs)
		[[ $name == mod ]] && continue
		echo "pub mod $name;"
	done
} >runtime/src/weights/mod.rs

if ((${#failed[@]})); then
	echo "failed: ${failed[*]}" >&2
	exit 1
fi
